const generateHeartbeat = (upProbability = 0.97, count = 30) => {
  return Array.from({ length: count }, () => Math.random() < upProbability ? 1 : 0)
}

const generateLatencyHistory = (base = 20, variance = 10, count = 30) => {
  return Array.from({ length: count }, () => Math.max(1, base + (Math.random() - 0.5) * variance * 2))
}

